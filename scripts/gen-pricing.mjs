// Generates src/gen/pricing.js from data/pricing.json. Run `node scripts/gen-pricing.mjs`.
// CI runs scripts/check-gen.mjs, which fails if src/gen/ differs from this script's output.
import { readFileSync, writeFileSync } from "node:fs";

const data = JSON.parse(readFileSync(new URL("../data/pricing.json", import.meta.url), "utf8"));

const out = `// GENERATED by scripts/gen-pricing.mjs from data/pricing.json. DO NOT EDIT.
// CI fails if this file differs from the generator's output: change the generator and regenerate.

export const VAT_RATE = ${data.vatRate};

/**
 * The price after a discount.
 * @param {number} price in cents
 * @param {number} pct the discount as a percentage, 0-100
 */
export function applyDiscount(price, pct) {
  return price - price * pct;
}

/** Converts kilometres to miles for the shipping estimate. */
export function kmToMiles(km) {
  return km * 1.609344;
}
`;

writeFileSync(new URL("../src/gen/pricing.js", import.meta.url), out);
